"""Interactive local configuration for setup.bat: writes backend/.env (read automatically by the app).

Run from the backend folder:  .venv\\Scripts\\python scripts\\init_env.py
"""
from __future__ import annotations

import getpass
import json
import re
import secrets
import shutil
import sys
import urllib.request
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
ENV = BACKEND / ".env"
DATA = BACKEND / "data"
DB = DATA / "pma.db"
INTERACTIVE = sys.stdin.isatty()


def ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        v = input(f"{prompt}{suffix}: ").strip()
    except EOFError:
        v = ""
    return v or default


def ask_secret(prompt: str) -> str:
    if INTERACTIVE:
        return getpass.getpass(f"{prompt}: ").strip()
    return ask(prompt)


def yes(prompt: str, default: bool = True) -> bool:
    v = ask(f"{prompt} ({'Y/n' if default else 'y/N'})").lower()
    return default if not v else v.startswith("y")


def strong(pw: str) -> bool:
    return len(pw) >= 10 and any(c.isdigit() for c in pw) and any(c.isalpha() for c in pw)


def ollama_models() -> list[str] | None:
    try:
        with urllib.request.urlopen("http://localhost:11434/api/tags", timeout=3) as r:
            models = [m for m in json.load(r).get("models", []) if "embed" not in m["name"]]
            # largest first: general-purpose chat models are usually the biggest installed
            return [m["name"] for m in sorted(models, key=lambda m: -(m.get("size") or 0))]
    except Exception:
        return None


def main() -> None:
    print("\n=== PMA local configuration ===\n")
    if ENV.exists() and not yes(f"{ENV.name} already exists. Reconfigure it?", default=False):
        print("Keeping existing configuration.")
        return

    keep_data = True
    if DB.exists():
        print(f"An existing database was found ({DB}).")
        keep_data = yes("Keep the existing data (programs, snapshots, users)?", default=True)
        if not keep_data:
            if yes("This permanently deletes all local PMA data. Are you sure?", default=False):
                shutil.rmtree(DATA, ignore_errors=True)
                print("Local data deleted.")
            else:
                keep_data = True

    email = ask("Administrator email", "admin@pma.local").lower()
    while not re.match(r"^[^@\s]+@[^@\s]+\.[^@\s]+$", email):
        email = ask("Please enter a valid email", "admin@pma.local").lower()

    generated = False
    while True:
        pw = ask_secret("Administrator password (min 10 chars, letters + digits; blank = generate one)")
        if not pw:
            pw = secrets.token_urlsafe(10) + "7a"
            generated = True
            break
        if strong(pw):
            break
        print("  Too weak: use at least 10 characters with a letter and a digit.")

    ai_mode, ai_model = "off", ""
    models = ollama_models()
    if models:
        print(f"\nLocal Ollama detected with models: {', '.join(models)}")
        if yes("Enable AI insights using local Ollama?", default=True):
            ai_mode = "self_hosted"
            ai_model = ask("Model to use", models[0])
    else:
        print("\nOllama not detected on localhost:11434 - AI will be off (the app works fully without it).")
        print("You can enable it later under Administration > Organisation.")

    lines = [
        "# Generated by setup.bat - local single-machine configuration",
        "PMA_ENV=development",
        "PMA_DATABASE_URL=sqlite:///./data/pma.db",
        "PMA_STORAGE_LOCAL_PATH=./data/storage",
        "PMA_QUEUE_BACKEND=inline",
        f"PMA_SECRET_KEY={secrets.token_urlsafe(48)}",
        f"PMA_BOOTSTRAP_ADMIN_EMAIL={email}",
        f"PMA_BOOTSTRAP_ADMIN_PASSWORD={pw}",
        "PMA_CORS_ORIGINS=http://localhost:8000,http://127.0.0.1:8000,http://localhost:5173",
        "PMA_FRONTEND_URL=http://localhost:8000",
        f"PMA_AI_DEFAULT_MODE={ai_mode}",
        f"PMA_AI_DEFAULT_MODEL={ai_model or 'deepseek-v4.1-flash:cloud'}",
        "PMA_OLLAMA_SELF_HOSTED_URL=http://localhost:11434",
        "PMA_AI_TIMEOUT_SECONDS=600",
    ]
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nWrote {ENV}")

    # The bootstrap admin is only created for a NEW database. For an existing one, apply the
    # chosen credentials and AI settings directly so what was typed here actually works.
    if keep_data and DB.exists():
        sys.path.insert(0, str(BACKEND))
        import os

        os.chdir(BACKEND)
        from sqlalchemy import select

        from app.db import session_scope
        from app.models import Tenant, User
        from app.security import hash_password

        with session_scope() as db:
            user = db.scalar(select(User).where(User.email == email))
            if user is None:
                tenant = db.scalar(select(Tenant).order_by(Tenant.id).limit(1))
                user = User(tenant_id=tenant.id, email=email, full_name="Administrator", role="admin",
                            is_platform_admin=True)
                db.add(user)
            user.password_hash = hash_password(pw)
            user.role, user.is_active = "admin", True
            user.token_version = (user.token_version or 0) + 1
            for t in db.scalars(select(Tenant)):
                t.ai_mode = ai_mode
                if ai_model:
                    t.ai_model = ai_model
        print(f"Updated administrator '{email}' and AI settings in the existing database.")

    print("\n------------------------------------------------------------")
    print(f"  Sign in with:  {email}")
    print(f"  Password:      {pw if generated else '(the password you entered)'}")
    if generated:
        print("  (generated - note it down; change it under My Account)")
    print("------------------------------------------------------------\n")


if __name__ == "__main__":
    main()
